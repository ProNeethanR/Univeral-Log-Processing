# TEST 6 — Replay verification (Phase 7)
# ---------------------------------------------------------------------------

def test_demo_replay_after_deactivation(
    raw_demo_bytes, registered_demo_profile, demo_parser
):
    """
    Verify historical replay after profile deactivation.

    Sequence:
      1. Normalize using active profile 1.0.0.
      2. Deactivate profile 1.0.0.
      3. Confirm normal ingestion lookup rejects it.
      4. Confirm historical lookup still retrieves it.
      5. Replay — deterministic normalization without reactivation.
    """
    mapper = OCSFMapper()
    records = split_raw_records(raw_demo_bytes)
    first_record_bytes = records[0][3]
    text = strip_record_terminator(first_record_bytes).decode("utf-8").strip()
    parsed_fields = demo_parser.parse(text)

    # Step 1: Normalize while active
    original_event = mapper.enrich_ocsf_headers(
        parsed_fields,
        mapper.map_syslog(
            parsed_fields,
            source_id=DEMO_FIXTURE_ID,
            profile_version=DEMO_PROFILE_VERSION,
        )
    )
    assert original_event.get("time") == EXPECTED_TIMESTAMPS[0]

    # Step 2: Deactivate
    deactivate_source_profile(DEMO_FIXTURE_ID, DEMO_PROFILE_VERSION)

    # Step 3: Normal ingestion lookup must reject
    with pytest.raises(ProfileInactiveError):
        get_source_profile(DEMO_FIXTURE_ID, DEMO_PROFILE_VERSION)

    # Step 4: Historical lookup must succeed
    historical_profile = get_historical_source_profile(DEMO_FIXTURE_ID, DEMO_PROFILE_VERSION)
    assert historical_profile == DEMO_PROFILE

    # Step 5: Replay produces deterministic output without reactivation
    replayed = mapper.replay_syslog(
        parsed_fields,
        source_id=DEMO_FIXTURE_ID,
        profile_version=DEMO_PROFILE_VERSION,
    )
    replayed_enriched = mapper.enrich_ocsf_headers(parsed_fields, replayed)

    assert replayed_enriched.get("time") == EXPECTED_TIMESTAMPS[0], (
        "Replay must produce identical timestamp as original normalization"
    )
    assert replayed_enriched["metadata"]["product"]["vendor_name"] == "Linux", (
        "Replay must resolve vendor from historical profile, not active profile"
    )
    assert dict(replayed_enriched) == dict(original_event), (
        "Replay output must be byte-for-byte identical to original normalization"
    )


