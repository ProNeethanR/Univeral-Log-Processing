def test_demo_profile_registration_and_persistence(tmp_path):
    """Register demo profile, verify persistence and reload.

    _clear_registry() is a TEST CLEANUP helper that deletes stored files.
    To simulate a process restart (in-memory state lost but storage intact),
    we zero the in-memory _profile_registry directly and then call
    configure_profile_storage to reload from the durable store.
    """
    import src.registry as reg_module

    storage = tmp_path / "persist-store"
    configure_profile_storage(storage)
    _clear_registry()

    register_source_profile(
        DEMO_FIXTURE_ID, DEMO_PROFILE_VERSION, DEMO_PROFILE, activate=True
    )

    # File persisted in storage
    profile_file = storage / f"{DEMO_FIXTURE_ID}__{DEMO_PROFILE_VERSION}.json"
    assert profile_file.exists(), "Profile JSON file must exist in durable storage"

    # Retrieve via active API
    retrieved = get_source_profile(DEMO_FIXTURE_ID, DEMO_PROFILE_VERSION)
    assert retrieved == DEMO_PROFILE

    # Simulate process restart: zero in-memory state WITHOUT deleting files.
    # This mimics a new process starting up and loading from the durable store.
    reg_module._profile_registry.clear()
    configure_profile_storage(storage)

    # Profile survives reload and is active
    reloaded = get_source_profile(DEMO_FIXTURE_ID, DEMO_PROFILE_VERSION)
    assert reloaded == DEMO_PROFILE

    profiles = list_source_profiles()
    assert (DEMO_FIXTURE_ID, DEMO_PROFILE_VERSION, ProfileState.ACTIVE) in profiles


