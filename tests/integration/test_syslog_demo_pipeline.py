def test_demo_pipeline_full_ocsf_pass(
    raw_demo_bytes, registered_demo_profile, demo_parser, ground_truth
):
    """
    Full pipeline: ingest → parse → Source Context inject → OCSF map → validate.

    Expected: OCSF validation PASS for all 7 events.
    Ground truth verified for key OCSF fields.
    """
    mapper = OCSFMapper()
    records = split_raw_records(raw_demo_bytes)
    assert len(records) == DEMO_EVENT_COUNT

    for i, (rec_idx, offset_start, offset_end, record_bytes) in enumerate(records):
        # 1. Raw byte preservation
        assert len(record_bytes) > 0, f"Event {i+1}: empty record bytes"

        # 2. Ingest raw bytes
        event = ingest_bytes(
            record_bytes,
            source_id=DEMO_FIXTURE_ID,
            input_format="syslog",
            profile_version=DEMO_PROFILE_VERSION,
            byte_offset_start=offset_start,
            byte_offset_end=offset_end,
            record_index=rec_idx,
        )

        # 3. SHA-256 integrity
        expected_hash = hashlib.sha256(record_bytes).hexdigest()
        assert event.sha256 == expected_hash, (
            f"Event {i+1}: SHA-256 mismatch after ingestion"
        )
        assert vault.verify(event.locator) is True, (
            f"Event {i+1}: vault integrity verification failed"
        )
        assert event.integrity_status == "verified", (
            f"Event {i+1}: expected integrity 'verified', got '{event.integrity_status}'"
        )

        # 4. vault metadata carries profile_version
        meta = vault.metadata(event.locator)
        assert meta.profile_version == DEMO_PROFILE_VERSION, (
            f"Event {i+1}: vault metadata must persist profile_version"
        )
        assert meta.source_id == DEMO_FIXTURE_ID

        # 5. Parse — strip line terminator for text parser
        text = strip_record_terminator(record_bytes).decode("utf-8").strip()
        parsed_fields = demo_parser.parse(text)
        assert parsed_fields, f"Event {i+1}: parser returned empty fields"

        # 6. Map with Source Profile context injection
        raw_mapped = mapper.map_syslog(
            parsed_fields,
            source_id=DEMO_FIXTURE_ID,
            profile_version=DEMO_PROFILE_VERSION,
        )

        # 7. Enrich OCSF headers
        enriched = mapper.enrich_ocsf_headers(parsed_fields, raw_mapped)

        # 8. OCSF validation — MUST PASS
        val_result = mapper.validator.validate(enriched)
        assert isinstance(val_result, OCSFValidationResult)
        assert val_result.ocsf_version == "1.3.0"
        assert val_result.is_valid is True, (
            f"Event {i+1}: OCSF validation must PASS for demo fixture "
            f"(all required fields supplied by Source Profile). "
            f"Errors: {[e.to_dict() for e in val_result.errors]}"
        )

        # 9. Policy field values
        for field, expected_val in POLICY_VALUES.items():
            assert field in enriched, f"Event {i+1}: policy field '{field}' missing"
            assert enriched[field] == expected_val, (
                f"Event {i+1}: policy field '{field}' expected {expected_val}, "
                f"got {enriched[field]}"
            )

        # 10. Authoritative timestamp from Source Profile — no fallback
        assert "time" in enriched, (
            f"Event {i+1}: 'time' must be present (supplied by Source Profile)"
        )
        assert enriched["time"] == EXPECTED_TIMESTAMPS[i], (
            f"Event {i+1}: timestamp mismatch.\n"
            f"  Expected (ground truth): {EXPECTED_TIMESTAMPS[i]}\n"
            f"  Actual:                  {enriched['time']}"
        )

        # 11. Authoritative metadata from Source Profile — no fallback
        assert "metadata" in enriched, (
            f"Event {i+1}: 'metadata' must be present (supplied by Source Profile)"
        )
        assert enriched["metadata"]["product"]["vendor_name"] == "Linux", (
            f"Event {i+1}: vendor_name must come ONLY from Source Profile"
        )
        assert enriched["metadata"]["product"]["name"] == "iptables", (
            f"Event {i+1}: product name must come ONLY from Source Profile"
        )

        # 12. Provenance: source profile id on MappingResult
        assert isinstance(enriched, MappingResult), (
            f"Event {i+1}: mapper must return MappingResult"
        )
        assert enriched.source_profile_id == f"{DEMO_FIXTURE_ID}:{DEMO_PROFILE_VERSION}", (
            f"Event {i+1}: MappingResult must record source_profile_id"
        )
        assert enriched.source_profile_version == DEMO_PROFILE_VERSION

        # 13. Injected fields provenance lineage
        injected_names = {f["field"] for f in enriched.injected_fields}
        assert "time" in injected_names, (
            f"Event {i+1}: 'time' must be recorded as injected from source_profile"
        )
        assert "metadata" in injected_names, (
            f"Event {i+1}: 'metadata' must be recorded as injected from source_profile"
        )
        for inj in enriched.injected_fields:
            assert inj.get("source") == "source_profile", (
                f"Event {i+1}: injected field '{inj['field']}' source must be "
                f"'source_profile', got '{inj.get('source')}'"
            )
            assert inj.get("profile_id") == f"{DEMO_FIXTURE_ID}:{DEMO_PROFILE_VERSION}"

        # 14. Ground truth key field verification
        gt_event = ground_truth[i]
        gt_ocsf = gt_event["expected_ocsf"]
        assert enriched["time"] == gt_ocsf["time"], (
            f"Event {i+1}: time does not match ground truth"
        )
        assert enriched["metadata"]["product"]["vendor_name"] == gt_ocsf["metadata"]["product"]["vendor_name"]
        assert enriched["metadata"]["product"]["name"] == gt_ocsf["metadata"]["product"]["name"]
        assert enriched["connection_info"]["protocol_name"] == gt_ocsf["connection_info"]["protocol_name"]
        assert enriched["connection_info"]["direction_id"] == gt_ocsf["connection_info"]["direction_id"], (
            f"Event {i+1}: direction_id mismatch vs ground truth. "
            f"Expected {gt_ocsf['connection_info']['direction_id']}, "
            f"got {enriched['connection_info']['direction_id']}"
        )
        if "src_endpoint" in gt_ocsf and "ip" in gt_ocsf["src_endpoint"]:
            assert enriched.get("src_endpoint", {}).get("ip") == gt_ocsf["src_endpoint"]["ip"]
        if "dst_endpoint" in gt_ocsf and "ip" in gt_ocsf["dst_endpoint"]:
            assert enriched.get("dst_endpoint", {}).get("ip") == gt_ocsf["dst_endpoint"]["ip"]

        # 15. No fabricated current-year or local-timezone fallbacks present
        # Absence of these guard assertions proves the framework's policy holds.
        # (If capture_year/timezone were missing, time would be absent — and
        # validation would FAIL. The PASS above proves they came from the profile.)


